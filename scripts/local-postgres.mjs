import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync, unlinkSync } from "node:fs";
import { resolve, join } from "node:path";
import { parse } from "dotenv";
const root = resolve(import.meta.dirname, "..");
const settings = parse(readFileSync(resolve(root, ".env")));
const home = resolve(root, ".local/postgresql");
const data = join(home, "data");
const bin = process.env.POSTGRES_BIN || (process.platform === "win32" ? "D:/postgresql/bin" : "");
const port = settings.POSTGRES_PORT || "5544";
if (!/^\d+$/.test(port) || Number(port) < 1024 || Number(port) > 65535) throw new Error("Invalid POSTGRES_PORT");
const env = { ...process.env, PGPASSWORD: settings.POSTGRES_ADMIN_PASSWORD };
function run(name, args, input, allowFailure = false) {
  const executable = bin ? join(bin, name + (process.platform === "win32" ? ".exe" : "")) : name;
  const result = spawnSync(executable, args, { env, input, encoding: "utf8", windowsHide: true,
    ...(name === "pg_ctl" && args.includes("start") ? { stdio: "ignore" } : {}) });
  if (!allowFailure && (result.error || result.status !== 0)) {
    console.error(result.error?.message || result.stderr || result.stdout);
    throw new Error(name + " failed");
  }
  return result;
}
mkdirSync(home, { recursive: true });
if (process.argv.includes("--stop")) {
  run("pg_ctl", ["-D", data, "-m", "fast", "-w", "stop"]);
  console.log("Stopped this project's PostgreSQL instance");
  process.exit(0);
}
if (!existsSync(join(data, "PG_VERSION"))) {
  if (!settings.POSTGRES_ADMIN_PASSWORD) throw new Error("Run npm run setup first");
  const passwordFile = join(home, "init-password.txt");
  writeFileSync(passwordFile, settings.POSTGRES_ADMIN_PASSWORD);
  try { run("initdb", ["-D", data, "-U", "short_admin", "--pwfile", passwordFile, "--auth-local=scram-sha-256", "--auth-host=scram-sha-256", "--encoding=UTF8", "--locale=C"]); }
  finally { unlinkSync(passwordFile); }
}
if (run("pg_ctl", ["-D", data, "status"], undefined, true).status !== 0)
  run("pg_ctl", ["-D", data, "-l", join(home, "postgres.log"), "-o", `-p ${port} -h 127.0.0.1`, "-w", "start"]);
const args = ["-h", "127.0.0.1", "-p", port, "-U", "short_admin", "-v", "ON_ERROR_STOP=1"];
if (!existsSync(join(home, "provisioned"))) {
  run("psql", [...args, "-d", "postgres"], "CREATE DATABASE short_url OWNER short_admin;");
  let sql = readFileSync(resolve(root, "infra/postgres-init.sql"), "utf8");
  for (const [key, variable] of [["AUTH_DB_PASSWORD", "auth_password"], ["LINK_DB_PASSWORD", "links_password"], ["ANALYTICS_DB_PASSWORD", "analytics_password"]]) {
    const value = settings[key];
    if (!/^[a-f0-9]{64}$/.test(value || "")) throw new Error("Local passwords must be generated by setup");
    sql = sql.replaceAll(":'" + variable + "'", "'" + value + "'");
  }
  run("psql", [...args, "-d", "short_url"], sql);
  writeFileSync(join(home, "provisioned"), "PostgreSQL dev and test databases provisioned\n");
}
console.log("Local PostgreSQL ready at 127.0.0.1:" + port + "; service schemas and test database are separate");
