import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { rootShortLinkPattern } from "@short/routing";

// Docker ใช้กฎชื่อสงวนเดียวกับ Vercel; สร้างไฟล์นี้ใหม่เมื่อแก้รายการชื่อ
const directory = resolve(import.meta.dirname, "../infra");
mkdirSync(directory, { recursive: true });
writeFileSync(resolve(directory, "nginx-short-links.conf"),
  `# Generated by node scripts/configure-nginx.mjs\n` +
  `location ~ "^/${rootShortLinkPattern}/?$" {\n` +
  `  proxy_pass http://gateway:3000;\n` +
  `  proxy_set_header Host $host;\n` +
  `  proxy_set_header X-Forwarded-For "";\n` +
  `  proxy_read_timeout 15s;\n` +
  `}\n`);
console.log("Docker frontend short-link routes configured.");
